// Command protoc-gen-grpcapi 为每个 proto Service 生成 server.Registration
// 适配器，消除手写 gRPC + gateway 注册样板。
//
// 生成物示例：
//
//	func NewEchoServiceRegistration(impl EchoServiceServer) server.Registration { ... }
//
// 只生成注册样板；策略、路由、错误体仍由 proto/项目代码声明。
package main

import (
	"fmt"

	grpcapiv1 "github.com/lynx-go/grpcapi/genproto/grpcapi/v1"
	"google.golang.org/genproto/googleapis/api/annotations"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

const (
	serverPkg  = protogen.GoImportPath("github.com/lynx-go/grpcapi/server")
	grpcPkg    = protogen.GoImportPath("google.golang.org/grpc")
	runtimePkg = protogen.GoImportPath("github.com/grpc-ecosystem/grpc-gateway/v2/runtime")
	contextPkg = protogen.GoImportPath("context")
)

func main() {
	protogen.Options{}.Run(generateInto)
}

// generateInto 是插件的全部逻辑（main 只负责 stdin/stdout），拆出以便
// golden 测试直接以 CodeGeneratorRequest 驱动。
func generateInto(gen *protogen.Plugin) error {
	gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
	for _, f := range gen.Files {
		if !f.Generate {
			continue
		}
		generateFile(gen, f)
	}
	return nil
}

func generateFile(gen *protogen.Plugin, file *protogen.File) {
	if len(file.Services) == 0 {
		return
	}
	filename := file.GeneratedFilenamePrefix + "_grpcapi.pb.go"
	g := gen.NewGeneratedFile(filename, file.GoImportPath)
	g.P("// Code generated by protoc-gen-grpcapi. DO NOT EDIT.")
	g.P("// source: ", file.Desc.Path())
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()

	api := fileAPI(file)
	for _, svc := range file.Services {
		generateService(g, file, svc, api)
	}
}

func fileAPI(file *protogen.File) string {
	opts := file.Desc.Options().(*descriptorpb.FileOptions)
	if opts == nil {
		return ""
	}
	ext := proto.GetExtension(opts, grpcapiv1.E_Api)
	spec, ok := ext.(*grpcapiv1.APISpec)
	if !ok || spec == nil {
		return ""
	}
	return spec.GetApi()
}

func generateService(g *protogen.GeneratedFile, file *protogen.File, svc *protogen.Service, api string) {
	fn := "New" + svc.GoName + "Registration"
	g.P("// ", fn, " 返回 ", svc.Desc.FullName(), " 的 server.Registration。")
	g.P("func ", fn, "(impl ", svc.GoName, "Server) ", g.QualifiedGoIdent(serverPkg.Ident("Registration")), " {")
	g.P("return ", g.QualifiedGoIdent(serverPkg.Ident("Registration")), "{")
	if api != "" {
		g.P("API: ", fmt.Sprintf("%q", api), ",")
	}
	g.P("Name: ", fmt.Sprintf("%q", string(svc.Desc.FullName())), ",")
	g.P("Descriptor: ", g.QualifiedGoIdent(file.GoDescriptorIdent), ".Services().ByName(", fmt.Sprintf("%q", svc.Desc.Name()), "),")
	g.P("RegisterGRPC: func(s *", g.QualifiedGoIdent(grpcPkg.Ident("Server")), ") {")
	g.P("Register", svc.GoName, "Server(s, impl)")
	g.P("},")
	if hasHTTP(svc) {
		g.P("RegisterHTTP: func(ctx ", g.QualifiedGoIdent(contextPkg.Ident("Context")), ", mux *", g.QualifiedGoIdent(runtimePkg.Ident("ServeMux")), ", conn ", g.QualifiedGoIdent(grpcPkg.Ident("ClientConnInterface")), ") error {")
		g.P("return Register", svc.GoName, "HandlerClient(ctx, mux, New", svc.GoName, "Client(conn))")
		g.P("},")
	}
	g.P("}")
	g.P("}")
	g.P()
}

func hasHTTP(svc *protogen.Service) bool {
	for _, m := range svc.Methods {
		opts := m.Desc.Options().(*descriptorpb.MethodOptions)
		if opts == nil {
			continue
		}
		ext := proto.GetExtension(opts, annotations.E_Http)
		if rule, ok := ext.(*annotations.HttpRule); ok && rule != nil {
			return true
		}
	}
	return false
}
